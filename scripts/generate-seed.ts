// Generates supabase/seed.sql from lib/demo/content.ts so the database demo
// data and the no-database demo mode never drift apart.
// Usage: npm run db:seed:generate
import { writeFileSync } from "node:fs";
import {
  demoCategories,
  demoContentBlocks,
  demoPackages,
  demoProducts,
  demoProjects,
  demoSettings,
} from "../lib/demo/content";

type Value = string | number | boolean | null | undefined | string[] | object;

const JSONB_COLUMNS = new Set(["specs", "components"]);

function lit(v: Value, column = ""): string {
  if (v === null || v === undefined) return "null";
  if (JSONB_COLUMNS.has(column)) return `${lit(JSON.stringify(v))}::jsonb`;
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "number") return String(v);
  if (Array.isArray(v) && v.every((x) => typeof x === "string")) {
    return v.length ? `array[${v.map((x) => lit(x)).join(", ")}]::text[]` : "'{}'::text[]";
  }
  if (typeof v === "object") return `${lit(JSON.stringify(v))}::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
}

function insert(table: string, rows: Record<string, Value>[], conflict: string): string {
  if (!rows.length) return "";
  const cols = Object.keys(rows[0]);
  const values = rows.map((r) => `  (${cols.map((c) => lit(r[c], c)).join(", ")})`).join(",\n");
  return `insert into public.${table} (${cols.join(", ")}) values\n${values}\non conflict (${conflict}) do nothing;\n`;
}

const strip = <T extends object>(o: T, keys: string[]) =>
  Object.fromEntries(Object.entries(o).filter(([k]) => !keys.includes(k))) as Record<string, Value>;

const sql = [
  "-- GENERATED by scripts/generate-seed.ts from lib/demo/content.ts — do not edit by hand.",
  "-- DEMONSTRATION DATA for the proposal preview. Packages, products and projects are",
  "-- marked is_sample = true; content blocks awaiting confirmation are marked",
  "-- needs_confirmation. A production-mode database hides both from the public.",
  "",
  insert("site_settings", [{ id: 1, ...(demoSettings as unknown as Record<string, Value>) }], "id"),
  insert("content_blocks", demoContentBlocks as unknown as Record<string, Value>[], "key"),
  insert("product_categories", demoCategories as unknown as Record<string, Value>[], "id"),
  insert("products", demoProducts.map((p) => strip(p, ["updated_at"])), "id"),
  insert("packages", demoPackages.map((p) => strip(p, ["updated_at"])), "id"),
  insert("projects", demoProjects.map((p) => strip(p, ["updated_at"])), "id"),
].join("\n");

writeFileSync("supabase/seed.sql", sql);
console.log("Wrote supabase/seed.sql");
